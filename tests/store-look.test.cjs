require('./register-typescript.cjs')
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('fs')
const path = require('path')
const L = require('../lib/commerce/store-look.ts')
const S = require('../lib/commerce/storefront.ts')
const read = (f) => fs.readFileSync(path.join(__dirname, '..', f), 'utf8')

test('layouts: four choices, tiles when unknown', () => {
  assert.deepEqual([...L.STORE_LAYOUTS], ['grid', 'big', 'list', 'compact'])
  assert.equal(S.readStorefront({}).layout, 'grid')
  assert.equal(S.readStorefront({ layout: 'list' }).layout, 'list')
  assert.equal(S.readStorefront({ layout: 'fancy' }).layout, 'grid')
})

test('Instagram: handle and post links cleaned, at most 9, no repeats', () => {
  assert.equal(L.cleanInstagramHandle('@asha.silks'), 'asha.silks')
  assert.equal(L.cleanInstagramHandle('https://www.instagram.com/asha_silks/?hl=en'), 'asha_silks')
  assert.equal(L.cleanInstagramHandle('not a handle!'), '')
  assert.equal(L.instagramPost('https://www.instagram.com/p/Cx1aB2cd/?igsh=abc'), 'p/Cx1aB2cd')
  assert.equal(L.instagramPost('https://instagram.com/asha/reel/AbCdE12/'), 'reel/AbCdE12')
  assert.equal(L.instagramPost('https://evil.com/p/Cx1aB2cd'), '')
  const posts = Array.from({ length: 12 }, (_, i) => `https://www.instagram.com/p/Post${i}xx/`)
  const s = S.readStorefront({ instagram: { handle: '@shop', posts: [...posts, posts[0], 'p/Post0xx'] } })
  assert.equal(s.instagram.handle, 'shop')
  assert.equal(s.instagram.posts.length, 9)
  assert.equal(s.instagram.posts[0], 'p/Post0xx')
})

test('wiring: store page uses the layout and shows Instagram embeds; settings screen stays browser-safe', () => {
  const page = read('app/s/[slug]/storefront.tsx')
  assert.match(page, /className=\{gridClass\}/)
  assert.match(page, /instagram\.com\/\$\{post\}\/embed/)
  const settings = read('components/commerce/storefront-settings.tsx')
  assert.match(settings, /from '@\/lib\/commerce\/store-look'/)
  assert.doesNotMatch(settings, /from '@\/lib\/commerce\/storefront'/)
  assert.doesNotMatch(read('lib/commerce/store-look.ts'), /^import /m)
})
