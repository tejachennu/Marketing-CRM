test('website settings are cleaned', () => {
  assert.deepEqual(W.readSite(null), W.DEFAULT_SITE)
  const s = W.readSite({ enabled: false, tagline: '  Hair   and skin  ', cover: 'http://insecure.jpg', gallery: ['https://a/1.jpg', 'https://a/1.jpg', 'javascript:x', ...Array.from({ length: 20 }, (_, i) => `https://a/${i + 2}.jpg`)], colour: '#7a2e4d', show: { team: false }, instagram: 'https://www.instagram.com/glow.studio/?hl=en', domainShows: 'store' })
  assert.equal(s.enabled, false)
  assert.equal(s.tagline, 'Hair and skin')
  assert.equal(s.cover, '', 'https only')
  assert.equal(s.gallery.length, W.MAX_GALLERY)
  assert.equal(s.gallery[0], 'https://a/1.jpg')
  assert.equal(s.colour, '#7A2E4D')
  assert.deepEqual(s.show, { prices: true, team: false, memberships: true, reviews: true })
  assert.equal(s.instagram, 'glow.studio')
  assert.equal(s.domainShows, 'store')
  assert.equal(W.readSite({ colour: 'red' }).colour, W.DEFAULT_SITE.colour)
})

test('which site the own domain opens', () => {
  assert.equal(W.domainOpens({ website: true, store: false, choice: 'store' }), 'website')
  assert.equal(W.domainOpens({ website: false, store: true, choice: 'website' }), 'store')
  assert.equal(W.domainOpens({ website: true, store: true, choice: 'store' }), 'store')
  assert.equal(W.domainOpens({ website: true, store: true, choice: 'website' }), 'website')
  assert.equal(W.domainOpens({ website: false, store: false, choice: 'website' }), null)
})

test('Open now, in India time, and the week', () => {
  const hours = { opens_at: '10:00', closes_at: '21:00', closed_weekdays: [2] }
  // 20 Nov 2026 is a Friday; 08:30 UTC = 14:00 IST
  assert.deepEqual(W.openStatus(hours, Date.parse('2026-11-20T08:30:00Z')), { open: true, text: 'Open now · closes 9 pm' })
  assert.deepEqual(W.openStatus(hours, Date.parse('2026-11-20T02:30:00Z')), { open: false, text: 'Opens today at 10 am' })
  assert.deepEqual(W.openStatus(hours, Date.parse('2026-11-20T16:30:00Z')), { open: false, text: 'Closed now · opens tomorrow 10 am' })
  // Monday night → Tuesday closed → opens Wednesday
  assert.deepEqual(W.openStatus(hours, Date.parse('2026-11-23T17:00:00Z')), { open: false, text: 'Closed now · opens Wednesday 10 am' })
  assert.deepEqual(W.openStatus(hours, Date.parse('2026-11-24T08:00:00Z')), { open: false, text: 'Closed today · opens tomorrow 10 am' })
  assert.equal(W.openStatus({ closed_weekdays: [0, 1, 2, 3, 4, 5, 6] }).text, 'Closed')
  const week = W.weekRows(hours, Date.parse('2026-11-20T08:30:00Z'))
  assert.equal(week[0].day, 'Monday')
  assert.equal(week[1].time, 'Closed')
  assert.equal(week.find((d) => d.today).day, 'Friday')
  assert.equal(week[0].time, '10 am – 9 pm')
  assert.equal(W.niceTime('09:30'), '9:30 am')
  assert.equal(W.niceTime('12:00'), '12 pm')
  assert.equal(W.duration(45), '45 min')
  assert.equal(W.duration(90), '1 h 30 min')
  assert.equal(W.duration(120), '2 h')
  assert.equal(W.fromPrice([0, 900, 300]), 300)
  assert.equal(W.fromPrice([0]), 0)
})

